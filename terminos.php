<h1>Términos y condiciones</h1>
<p>ArenaCJD es un sistema de gestión deportiva. Al crear una cuenta, el usuario se compromete a proporcionar datos correctos, proteger sus credenciales y utilizar las funciones disponibles según su rol.</p>
<h2>Cuentas y acceso</h2>
<p>Las cuentas pueden requerir aprobación administrativa. Los permisos de administrador, organizador y participante determinan las acciones disponibles dentro del sistema.</p>
<h2>Uso de competiciones</h2>
<p>Los torneos, inscripciones, sorteos, enfrentamientos y resultados registrados deben corresponder a la actividad que se administra. Los responsables del torneo deben revisar la información antes de confirmar cambios.</p>
<h2>Seguridad</h2>
<p>No se deben compartir contraseñas ni intentar acceder a funciones para las que la cuenta no dispone de permisos.</p>
