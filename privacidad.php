<h1>Política de privacidad</h1>
<p>ArenaCJD utiliza los datos de cuenta necesarios para autenticar usuarios, gestionar permisos, inscripciones y participación en torneos.</p>
<h2>Datos de cuenta</h2>
<p>El sistema puede almacenar nombre, nombre de usuario, correo, contraseña protegida mediante hash, roles, estado de la cuenta y datos de recuperación configurados por el usuario.</p>
<h2>Contraseñas y recuperación</h2>
<p>Las contraseñas y respuestas de recuperación se almacenan protegidas mediante hash y no deben mostrarse en texto plano.</p>
<h2>Información pública</h2>
<p>La portada pública puede mostrar información competitiva como torneos, enfrentamientos y resultados, pero no expone credenciales de acceso.</p>
